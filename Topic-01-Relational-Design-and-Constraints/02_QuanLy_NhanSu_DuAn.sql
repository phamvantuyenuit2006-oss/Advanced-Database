USE master;
GO
IF EXISTS (SELECT name FROM sys.databases WHERE name = N'QuanLyNhanSuDuAn')
    DROP DATABASE QuanLyNhanSuDuAn;
GO
CREATE DATABASE QuanLyNhanSuDuAn;
GO
USE QuanLyNhanSuDuAn;
GO

CREATE TABLE PHONGBAN (
    MAPHG INT NOT NULL,
    TENPHG NVARCHAR(50) NOT NULL,
    TRPHG CHAR(9) NULL,
    NG_NHANCHUC DATE NULL,
    CONSTRAINT PK_PhongBan PRIMARY KEY (MAPHG)
);
GO

CREATE TABLE NHANVIEN (
    MANV CHAR(9) NOT NULL,
    HONV NVARCHAR(20) NOT NULL,
    TENLOT NVARCHAR(20) NULL,
    TENNV NVARCHAR(20) NOT NULL,
    NGSINH DATE NOT NULL,
    DCHI NVARCHAR(100) NULL,
    PHAI NVARCHAR(3) CHECK (PHAI IN (N'Nam', N'Nữ')),
    LUONG DECIMAL(12,2) CHECK (LUONG > 0),
    MA_NQL CHAR(9) NULL,
    PHG INT NULL,
    CONSTRAINT PK_NhanVien PRIMARY KEY (MANV),
    CONSTRAINT FK_NhanVien_NQL FOREIGN KEY (MA_NQL) REFERENCES NHANVIEN(MANV),
    CONSTRAINT FK_NhanVien_Phong FOREIGN KEY (PHG) REFERENCES PHONGBAN(MAPHG)
);
GO

ALTER TABLE PHONGBAN
ADD CONSTRAINT FK_PhongBan_TrPhong FOREIGN KEY (TRPHG) REFERENCES NHANVIEN(MANV);
GO

CREATE TABLE DUAN (
    MADA INT NOT NULL,
    TENDA NVARCHAR(100) NOT NULL,
    DDIEM_DA NVARCHAR(100) NOT NULL,
    PHONG INT NOT NULL,
    CONSTRAINT PK_DuAn PRIMARY KEY (MADA),
    CONSTRAINT FK_DuAn_Phong FOREIGN KEY (PHONG) REFERENCES PHONGBAN(MAPHG)
);
GO

CREATE TABLE THAMGIA (
    MANV CHAR(9) NOT NULL,
    MADA INT NOT NULL,
    THOIGIAN DECIMAL(5,1) CHECK (THOIGIAN >= 0),
    CONSTRAINT PK_ThamGiaDA PRIMARY KEY (MANV, MADA),
    CONSTRAINT FK_TG_NV FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV),
    CONSTRAINT FK_TG_DA FOREIGN KEY (MADA) REFERENCES DUAN(MADA)
);
GO

CREATE TABLE NGUOICON (
    MANV CHAR(9) NOT NULL,
    TENTN NVARCHAR(50) NOT NULL,
    PHAI NVARCHAR(3) CHECK (PHAI IN (N'Nam', N'Nữ')),
    NGSINH DATE NULL,
    QUANHE NVARCHAR(20) NOT NULL,
    CONSTRAINT PK_NguoiCon PRIMARY KEY (MANV, TENTN),
    CONSTRAINT FK_NguoiCon_NV FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV) ON DELETE CASCADE
);
GO

